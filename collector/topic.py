# -*- coding: utf-8 -*-
"""主题分类：`apply` / `non_apply` / `other` —— **每条都要能说出命中了什么词**。

## 为什么是规则而不是模型

用户问"这条为什么进我的首屏"，答案必须是**一句话能复述的关键词**：「标题里有『推免』」。
模型给的是概率，复述出来是"模型觉得像"，那在这种情况下等于没说。
而且模型不可回归：词表改了能跑测试，模型换了只能重新抽检。

## 三档口径（与协调者对齐）

- `apply`：**报考相关** —— 推免/招生简章/招生章程/专业目录/报名/报考点/夏令营/复试/调剂/
  硕士招生/博士招生/申请考核/直博。这是"我还能不能报、怎么报、什么时候截止"的那一类。
- `non_apply`：**在读/录取之后**的事务 —— 博士后/四六级/名单公示/拟录取/答辩/学位论文/
  竞赛/教学安排/选课/注册/报到/教师资格/奖学金/招聘/讲座。它们对招生**有信息量**，
  但用户不会因为错过它们而失去一个报考机会。
- `other`：两边都不像（学院新闻、活动报道、导航页…）。

## 权重与优先级（都来自实测错判）

1. **标题优先，且一票定档。** 标题是编辑给这条公告定的名，比正文里的零散词可靠得多。
2. **`non_apply` 强词在标题里出现时压过 `apply`。** 真实错判：
   「2026年硕士研究生拟录取名单公示」既含"硕士"（apply）又含"拟录取/名单公示"（non_apply），
   它显然是后者。所以先查 non_apply 强词。
3. 正文只做**分档平票时的补充**，且要求净胜 2 分以上，避免"正文提到一次"就翻档。

归属：A（数据管道）。下游**只读 `topic` / `topic_hits`，不要自己再判**。
"""
import re

# 标题里出现这些 → 直接 non_apply（强词，优先级最高）
NON_APPLY_STRONG = (
    "拟录取", "名单公示", "录取名单", "公示", "答辩", "学位论文", "博士后",
    "四六级", "四、六级", " CET", "CET-", "教师资格", "奖学金", "选课", "注册", "报到", "入学须知",
    "开题", "中期检查", "学位授予", "毕业生就业", "毕业图像", "毕业论文",
    "评优", "成绩查询", "教学安排",
    "调档", "组织关系", "户口", "竞赛", "暑期学校",
    "考试安排", "课程", "免修", "专业实践", "学籍", "图像采集", "就业",
    "论文送审", "双盲审", "培养方案", "导师", "奖助", "助学贷款", "档案",
    "大赛", "比赛", "赛事", "体检", "考核名单", "进入考核",
)

# 标题里出现这些 → `other`（既不是报考，也不是在读事务：新闻、活动、招聘、讲座…）
OTHER_STRONG = (
    "讲座", "讲坛", "论坛", "报告会", "学术报告", "研讨会", "工作坊", "培训", "招聘",
    "夏令营活动", "成功举办", "举行", "荣获", "获奖", "表彰", "风采", "团队",
    "宣传片", "直播", "回放", "导航", "联系我们", "文件汇总", "快速通道", "办事指南",
    "值班", "宣讲会", "服务中心",
)

# 标题里出现这些 → apply
APPLY_WORDS = (
    "推免", "免试", "招生", "专业目录", "招生目录", "报名", "报考",
    "报考点", "网报", "夏令营", "预推免", "复试", "调剂", "申请考核", "直博",
    "专项计划", "优秀大学生", "学制", "培养费用", "学费标准",
)

# 正文补充判据（权重 1，且要净胜 2）
APPLY_BODY = ("报名", "报考", "推免", "免试", "复试", "调剂", "招生简章", "招生章程",
              "专业目录", "夏令营", "申请考核", "网上报名", "报考点", "申报", "遴选")
NON_APPLY_BODY = ("拟录取", "名单公示", "答辩", "学位论文", "博士后", "四六级",
                  "选课", "注册", "报到", "奖学金", "讲座", "论坛", "竞赛",
                  "教学安排", "教师资格", "开题", "中期检查", "学位授予")

MAX_HITS = 8

# 标题只是机构名的形态。用在 ②'：这类页面的正文往往很长（导航、简介、团队介绍），
# 但它不是"一条公告"，归到 other 比硬塞进 apply/non_apply 更诚实。
ORG_TITLE_RE = re.compile(r"(学院|大学|研究院|研究所|研究中心|学部|系)$")


def _hits(text, words):
    return [w.strip() for w in words if w in (text or "")]


def classify(rec):
    """返回 `(topic, hits)`。`hits` 是命中的关键词（最多 8 个），按命中顺序。"""
    title = rec.get("title") or ""
    body = rec.get("body_text") or ""

    # ① 标题里的 non_apply 强词：一票定档
    hits = _hits(title, NON_APPLY_STRONG)
    if hits:
        return "non_apply", hits[:MAX_HITS]

    # ①' 标题里的"别的东西"（新闻/活动/招聘/讲座）：也一票定档
    hits = _hits(title, OTHER_STRONG)
    if hits:
        return "other", hits[:MAX_HITS]

    # ② 标题里的 apply 词
    hits = _hits(title, APPLY_WORDS)
    if hits:
        return "apply", hits[:MAX_HITS]

    # ②' 标题只是个机构名（「北京大学软件与微电子学院」「经管 | 金融科技团队」）：
    #     它不是一条公告的标题，正文再长也不构成报考信息。
    if len(title.strip()) <= 24 and ORG_TITLE_RE.search(title.strip()):
        return "other", ["title_is_org_name"]

    # ③ 正文净胜分（只做补充）：平票时按"更像在读事务"处理，
    #    因为 apply 的正文里几乎必然出现报名/报考这类动词，而只有一两个
    #    "竞赛/公示"词的正文，通常真的是在读事务。
    a = _hits(body, APPLY_BODY)
    n = _hits(body, NON_APPLY_BODY)
    if len(a) - len(n) >= 2:
        return "apply", a[:MAX_HITS]
    if len(n) >= 2 and len(n) > len(a):
        return "non_apply", n[:MAX_HITS]
    if len(a) >= 2 and len(a) > len(n):
        return "apply", a[:MAX_HITS]
    return "other", (a + n)[:MAX_HITS]
