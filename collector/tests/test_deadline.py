# -*- coding: utf-8 -*-
"""字段抽取回归测试。不依赖 pytest，直接跑：

    cd collector && python tests/test_deadline.py

为什么要它：deadline 和邮箱这类字段是靠正则堆出来的，规则一改就可能悄悄改坏
（真实发生过：`\\w` 是 Unicode 的，邮箱把中文吃进去了；宽窗口让截止日跨句错判）。
这三个人谁调词表谁先跑这个，绿了再提交。

归属：A 维护，B 加案例随便加，**但不要把已有的案例删掉改成通过**。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import fields          # noqa: E402

FAILED = []


def check(name, got, want):
    ok = got == want
    print(f"  {'PASS' if ok else 'FAIL'}  {name}")
    if not ok:
        print(f"        期望 {want!r}  实际 {got!r}")
        FAILED.append(name)


def dl(body, publish):
    return fields.extract_fields("测试公告", body, publish=publish)[ "deadline"]


print("== deadline：带年份 ==")
check("截止时间：2026年9月20日",
      dl("截止时间为2026年9月20日，逾期不再受理。", "2026-06-15"), "2026-09-20")
check("申请截止日期：2026年10月8日",
      dl("申请截止日期：2026年10月8日。", "2026-09-01"), "2026-10-08")

print("\n== deadline：不带年份（中文公告最常见的写法）==")
check("请于9月15日前将材料发送至邮箱",
      dl("请于9月15日前将申请材料发送至 yzb@example.edu.cn。", "2026-06-15"), "2026-09-15")
check("9月15日前提交",
      dl("纸质材料请于9月15日前提交至学院研究生科。", "2026-06-15"), "2026-09-15")
check("9.15 前发送",
      dl("推荐信请于9.15前发送至推荐人邮箱。", "2026-06-15"), "2026-09-15")

print("\n== deadline：日期区间取末尾 ==")
check("报名时间：2026年9月1日至2026年9月15日",
      dl("报名时间：2026年9月1日至2026年9月15日。", "2026-06-15"), "2026-09-15")
check("报名时间：9月1日—9月15日",
      dl("报名时间：9月1日—9月15日，请按时提交。", "2026-06-15"), "2026-09-15")

print("\n== deadline：跨句噪声不能误判（v1 的真实 bug）==")
check("会议日期不得被当成截止日",
      dl("学院会议于2026年3月31日召开。请于9月15日前提交材料。", "2026-06-15"),
      "2026-09-15")
check("早于发布日的无年份日期顺延下一年",
      dl("请于5月10日前提交申请材料。", "2026-06-15"), "2027-05-10")

print("\n== deadline：应该为 None 的情况 ==")
check("没有截止语境",
      dl("最终以我校研究生招生网2027年招生简章及专业目录（预计9月发布）为准。",
         "2026-06-15"), None)
check("日期超出 400 天窗口",
      dl("截止时间为2028年9月20日。", "2026-06-15"), None)
check("正文为空", dl("", "2026-06-15"), None)

print("\n== 邮箱：不能把中文吃进去（v1 的真实 bug）==")
r = fields.extract_fields("测试", "电子版发送至teacher03@zju.edu.cn邮箱，抄送 a.b-c@x.co.uk。", "2026-06-15")
check("邮箱只含 ASCII", r["contact"]["email"], "teacher03@zju.edu.cn")
r = fields.extract_fields("测试", "材料发送至 teacher04@zju.edu.cn 即可。", "2026-06-15")
check("下划线邮箱", r["contact"]["email"], "teacher04@zju.edu.cn")

print("\n== 专业：不能全文匹配泛词（v1 的真实 bug）==")
r = fields.extract_fields("关于2026年秋季学期研究生老生注册的通知",
                          "请各位研究生按时注册，遵守学校管理规定，做好教育工作。",
                          "2026-07-27")
check("泛词不产生专业", r["majors"], [])
r = fields.extract_fields("物理学院2027年硕士研究生招生专业目录", "招收物理学专业硕士。", "2026-06-15")
check("标题里的专业要保留", r["majors"], ["物理学"])

print("\n== deadline：录取后义务不能当报名截止（来自真实数据的错判）==")
check("体检表寄达日不是报名截止",
      dl("（四）我院拟录取的推免生请于2027年3月自行到当地二甲及以上医院体检，"
         "并于2027年3月31日前将体检表寄达我院。", "2026-09-10"), None)
check("但同一句确实在讲报名时仍要认",
      dl("请于9月15日前将报名材料寄达我院。", "2026-06-15"), "2026-09-15")

print("\n== deadline：区间里的无年份日期（来自真实数据的错判）==")
check("括号里的预报名不能抢走正式报名",
      dl("（一）考生应在规定时间登录研招网参加报名，报名时间为2026年10月15日至10月24日"
         "（预报名时间为2026年10月9日至10月12日），每日9:00—22:00。", "2026-10-08"),
      "2026-10-24")

print("\n== deadline：日期顺序颠倒时取离关键词最近的 ==")
check("考试时间在前、报名截止在后",
      dl("考试时间为10月20日，报名截止9月15日。", "2026-06-15"), "2026-09-15")

print("\n== deadline：附件报名窗口增强 ==")
check("全角连接号", dl("2026年10月8日－10月21日开放时间", "2026-09-01"), "2026-10-21")
check("带时分的开放第二轮报名", dl("9月24日21:00-9月26日17:00开放第二轮报名", "2026-09-01"), "2026-09-26")
check("带时分的报名区间", dl("9月14日8:00至9月28日17:00报名时间", "2026-09-01"), "2026-09-28")

print("\n== 档位：'截止' 优先于 '报名时间' ==")
check("高档次优先",
      dl("报名时间：2026年9月1日。材料提交截止时间为2026年9月20日。", "2026-06-15"),
      "2026-09-20")

print()
if FAILED:
    print(f"❌ {len(FAILED)} 个用例失败：{FAILED}")
    sys.exit(1)
print("✅ 全部通过")
